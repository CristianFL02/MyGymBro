CREATE TABLE vinculacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrenador_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    tipo_vinculacion VARCHAR(255) NOT NULL,
    estado_vinculacion VARCHAR(255) NOT NULL,
    fecha_solicitud TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_vinculacion_entrenador FOREIGN KEY (entrenador_id) REFERENCES usuarios(id),
    CONSTRAINT fk_vinculacion_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_vinculacion_solicitud
    ON vinculacion(entrenador_id, cliente_id, tipo_vinculacion, estado_vinculacion);
